#!/usr/bin/env python3
"""Builds the English dictionary used by the portal.

Source of truth: i18n/en.json  ({ "<Arabic text>": "<English text>" }).
  python3 tools/i18n_build.py merge   -> folds i18n/tr/*.tsv (index<TAB>English, index = row of i18n/strings.json) into en.json
  python3 tools/i18n_build.py         -> checks en.json against i18n/strings.json and writes src/I18nDict.gs

Re-run tools/i18n_extract.js after changing interface text; this script lists any text that still needs an English line.
"""
import json, re, sys, glob, hashlib, os

ROOT = os.path.join(os.path.dirname(__file__), '..')
P = lambda *a: os.path.join(ROOT, *a)
AR = re.compile(r'[ء-ي]')
PH = re.compile(r'\{[A-Za-z0-9_]+\}')
# Arabic deliberately kept inside English text (sheet names users must match, the language switch label)
AR_OK = ('الأوصاف', 'الكفاءات', 'الموظفين', 'الكود', 'الاسم', 'يُحذف', 'عربي', 'امسح الحركات')

def load_en():
    try:
        return json.load(open(P('i18n', 'en.json'), encoding='utf-8'))
    except FileNotFoundError:
        return {}

def save_en(en):
    with open(P('i18n', 'en.json'), 'w', encoding='utf-8') as f:
        json.dump(dict(sorted(en.items())), f, ensure_ascii=False, indent=0)
        f.write('\n')

def merge():
    strings = json.load(open(P('i18n', 'strings.json'), encoding='utf-8'))
    en = load_en()
    for path in sorted(glob.glob(P('i18n', 'tr', '*.tsv'))):
        for line in open(path, encoding='utf-8'):
            line = line.rstrip('\n')
            if not line.strip():
                continue
            i, t = line.split('\t', 1)
            en[strings[int(i)]['k']] = t
    save_en(en)
    print('en.json:', len(en), 'entries')

def check_and_write():
    strings = json.load(open(P('i18n', 'strings.json'), encoding='utf-8'))
    en = load_en()
    problems = []
    missing = [s['k'] for s in strings if s['k'] not in en]
    for k, v in en.items():
        if sorted(PH.findall(k)) != sorted(PH.findall(v)):
            problems.append('placeholders differ: %r -> %r' % (k, v))
        rest = v
        for ok in AR_OK:
            rest = rest.replace(ok, '')
        if AR.search(rest):
            problems.append('Arabic left in English: %r' % v)
    for p in problems:
        print('!', p)
    if missing:
        print('%d texts need an English line:' % len(missing))
        for m in missing[:50]:
            print('  -', m)
    body = json.dumps(en, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
    ver = hashlib.sha1(body.encode('utf-8')).hexdigest()[:10]
    # v0.35.0: the dictionary itself is an HTML file, read only when English is needed — every server call used to
    # parse 570 KB of .gs code even for Arabic users
    with open(P('src', 'I18nEn.html'), 'w', encoding='utf-8') as f:
        f.write(body)
    with open(P('src', 'I18nDict.gs'), 'w', encoding='utf-8') as f:
        f.write('/** I18nDict.gs — GENERATED by tools/i18n_build.py from i18n/en.json. Do not edit by hand.\n')
        f.write(' *  The English dictionary is in I18nEn.html (plain JSON), loaded on first use (i18nEn_). */\n')
        f.write("var I18N_VERSION = '%s';\n" % ver)
        f.write('var I18N_EN_ = null;\n')
        f.write("function i18nEn_() { return I18N_EN_ || (I18N_EN_ = JSON.parse(HtmlService.createHtmlOutputFromFile('I18nEn').getContent())); }\n")
        f.write("function i18nEnText_() { return I18N_EN_ ? JSON.stringify(I18N_EN_) : HtmlService.createHtmlOutputFromFile('I18nEn').getContent(); }\n")
    print('src/I18nDict.gs written: %d entries, version %s, %d problems, %d missing' % (len(en), ver, len(problems), len(missing)))
    write_names()
    return 1 if problems else 0

def write_names():
    ns = {}
    exec(open(P('i18n', 'names_en.py'), encoding='utf-8').read(), ns)
    with open(P('src', 'EnNamesDict.gs'), 'w', encoding='utf-8') as f:
        f.write('/** EnNamesDict.gs — GENERATED by tools/i18n_build.py from i18n/names_en.py. English names filled where empty. */\n')
        f.write('var EN_JOB_NAMES = ' + json.dumps(ns['JOBS'], ensure_ascii=False, sort_keys=True) + ';\n')
        f.write('var EN_UNIT_NAMES = ' + json.dumps(ns['UNITS'], ensure_ascii=False, sort_keys=True) + ';\n')
    print('src/EnNamesDict.gs written: %d jobs, %d units' % (len(ns['JOBS']), len(ns['UNITS'])))

if __name__ == '__main__':
    if len(sys.argv) > 1 and sys.argv[1] == 'merge':
        merge()
    sys.exit(check_and_write())
