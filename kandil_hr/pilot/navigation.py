@frappe.whitelist(methods=["GET"])
def request_actions(name):
	enabled_guard()
	doc = frappe.get_doc("Kandil Hiring Request", name)
	doc.check_permission("read")
	step = next((row for row in doc.approval_steps if row.decision == "Pending"), None)
	role = (
		{
			"Headcount Exception": "Kandil Sector Approver",
			"Department Approval": "Kandil Approver",
			"HR Approval": "Kandil Recruiter",
			"Sector Approval": "Kandil Sector Approver",
			"CEO Approval": "Kandil CEO Approver",
			"Board Approval": "Kandil Board Approver",
		}.get(step.authority)
		if step
		else None
	)
	decide = bool(
		doc.status == "Pending"
		and step
		and can_act(doc, step.principal)
		and role in frappe.get_roles(step.principal)
	)
	from kandil_hr.foundation.security import request_scope
	from kandil_hr.recruitment.privacy import can_read_notes

	board_record = False
	board_members = []
	board_files = []
	if (
		frappe.conf.get("kandil_parity_enabled")
		and doc.status == "Pending"
		and step
		and step.authority == "Board Approval"
	):
		from kandil_hr.recruitment.authority import interested_users

		policy = frappe.parse_json(doc.route_snapshot or "{}").get("policy", {})
		user = frappe.session.user
		interests = interested_users(doc)
		board_members = [
			member
			for member in (step.principal, step.get("board_vice"))
			if member
			and member not in interests
			and frappe.db.get_value("User", member, "enabled")
			and "Kandil Board Approver" in frappe.get_roles(member)
		]
		can_manage = request_scope(doc, user, "manage") and user not in interests
		decide = bool(can_manage and user in board_members)
		board_record = bool(
			can_manage
			and user == policy.get("exception_approver")
			and "Kandil Sector Approver" in frappe.get_roles(user)
			and board_members
		)
		if board_record:
			for file in frappe.get_all(
				"File",
				filters={"attached_to_doctype": doc.doctype, "attached_to_name": doc.name, "is_private": 1},
				fields=["name", "file_name"],
				order_by="creation desc",
				limit_page_length=100,
			):
				if frappe.get_doc("File", file.name).has_permission("read"):
					board_files.append(dict(name=file.name, label=file.file_name))
	return dict(
		board_record=board_record,
		board_members=board_members,
		board_files=board_files,
		headcount_preview=bool(
			frappe.conf.get("kandil_parity_enabled")
			and request_scope(doc)
			and all(
				frappe.get_doc("Kandil Capacity", capacity).has_permission("read")
				for capacity in {row.capacity for row in doc.lines}
			)
		),
		confidential_notes=can_read_notes(doc),
		correct_approved=bool(
			frappe.conf.get("kandil_parity_enabled")
			and not doc.amends
			and doc.status in ("Approved", "Closed", "Filled")
			and "Kandil Recruiter" in frappe.get_roles()
			and request_scope(doc, frappe.session.user, "manage")
		),
		extended=bool(frappe.conf.get("kandil_parity_enabled")),
		step_id=step.step_key if step and frappe.conf.get("kandil_parity_enabled") else None,
		expected_version=str(doc.modified),
		revise=doc.status == "Returned" and doc.requested_by == frappe.session.user,
		amend=doc.status in ["Approved", "Filled"]
		and not doc.get("amends")
		and (doc.requested_by == frappe.session.user or "Kandil Recruiter" in frappe.get_roles()),
		review=bool(step and decide and step.authority == "HR Approval"),
		status=doc.status,
		submit=doc.status == "Draft" and doc.requested_by == frappe.session.user,
		decide=decide,
		cancel=doc.status in ["Draft", "Pending", "Approved"]
		and (
			doc.requested_by == frappe.session.user
			or bool({"Kandil Recruiter", "Kandil Sector Approver"}.intersection(frappe.get_roles()))
		),
		next_authority=step.authority if step and doc.status == "Pending" else None,
	)


@frappe.whitelist(methods=["GET"])
def offer_actions(name):
	enabled_guard()
	offer = frappe.get_doc("Job Offer", name)
	offer.check_permission("read")
	result = dict(
		managed=False, record_outcome=False, outcome=offer.get("custom_kandil_outcome") or "Pending"
	)
	if not offer.job_applicant:
		return result
	applicant = frappe.get_doc("Job Applicant", offer.job_applicant)
	applicant.check_permission("read")
	if not applicant.job_title:
		return result
	opening = frappe.get_doc("Job Opening", applicant.job_title)
	opening.check_permission("read")
	if not opening.get("custom_kandil_request"):
		return result
	result["managed"] = True
	request = frappe.get_doc("Kandil Hiring Request", opening.custom_kandil_request)
	request.check_permission("read")
	if frappe.conf.get("kandil_parity_enabled"):
		from kandil_hr.foundation.security import request_scope

		result.update(
			request=request.name,
			expected_version=str(request.modified),
			joining_voided=bool(offer.get("custom_kandil_joining_voided")),
			void_joining=(
				"Kandil Recruiter" in frappe.get_roles()
				and frappe.db.get_value("Kandil Organization Settings", request.company, "hr_approver")
				== frappe.session.user
				and request_scope(request, frappe.session.user, "manage")
				and result["outcome"] == "Joined"
				and not offer.get("custom_kandil_joining_voided")
				and request.status in ("Approved", "Closed")
				and opening.custom_kandil_vacancy_state not in ("Closed", "Cancelled")
			),
		)
	result["record_outcome"] = (
		"Kandil Recruiter" in frappe.get_roles()
		and offer.docstatus == 1
		and offer.status == "Accepted"
		and result["outcome"] == "Pending"
		and request.status == "Approved"
	)
	return result
