def has_app_permission():
	return bool(
		frappe.conf.get("kandil_pilot_enabled")
		and frappe.session.user != "Guest"
		and {
			"Kandil Requester",
			"Kandil Approver",
			"Kandil Recruiter",
			"Kandil Sector Approver",
			"System Manager",
			"Kandil CEO Approver",
			"Kandil Board Approver",
		}.intersection(frappe.get_roles())
	)


